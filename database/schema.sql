CREATE DATABASE IF NOT EXISTS controle_estoque CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE controle_estoque;

CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, google_id VARCHAR(128) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL, email VARCHAR(190) NOT NULL UNIQUE, picture TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS products (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, sku VARCHAR(64) NOT NULL UNIQUE,
 name VARCHAR(160) NOT NULL, category VARCHAR(100) NOT NULL DEFAULT 'Geral',
 unit VARCHAR(24) NOT NULL DEFAULT 'un', quantity DECIMAL(12,3) NOT NULL DEFAULT 0,
 minimum_quantity DECIMAL(12,3) NOT NULL DEFAULT 0, cost DECIMAL(12,2) NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_products_name (name), INDEX idx_products_category (category)
);
CREATE TABLE IF NOT EXISTS movements (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, product_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL, type ENUM('entrada','saida') NOT NULL,
 quantity DECIMAL(12,3) NOT NULL, note VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_movement_product FOREIGN KEY (product_id) REFERENCES products(id),
 CONSTRAINT fk_movement_user FOREIGN KEY (user_id) REFERENCES users(id),
 INDEX idx_movements_created (created_at), INDEX idx_movements_type (type)
);
